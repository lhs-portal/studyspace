// study-engine.js - LHS StudySpace Frontend Engine (Full Screen & Collapsible Sidebar)
let globalNotesIndex = [];
let currentSubject = "";
let isSidebarOpen = true;
let isReaderMaximized = false;

// Inject sleek custom thin scrollbar styles dynamically
(function injectSleekScrollbars() {
  if (document.getElementById('studyHubScrollStyles')) return;
  const style = document.createElement('style');
  style.id = 'studyHubScrollStyles';
  style.innerHTML = `
    #studyHubContainer *::-webkit-scrollbar {
      width: 5px;
      height: 5px;
    }
    #studyHubContainer *::-webkit-scrollbar-track {
      background: transparent;
    }
    #studyHubContainer *::-webkit-scrollbar-thumb {
      background: #334155;
      border-radius: 9999px;
    }
    #studyHubContainer *::-webkit-scrollbar-thumb:hover {
      background: #10b981;
    }
  `;
  document.head.appendChild(style);
})();

// 1. Fetch index map generated by Apps Script
async function initStudyEngine() {
  try {
    const res = await fetch('notes/notes-index.json');
    globalNotesIndex = await res.json();
    console.log(`Study Engine loaded: ${globalNotesIndex.length} subtopics mapped.`);
  } catch (err) {
    console.error('Failed to load notes index:', err);
  }
}

// 2. Initialize Study Hub View
function loadStudyHub(containerId = 'studyHubContainer') {
  const container = document.getElementById(containerId);
  if (!container) return;

  if (!globalNotesIndex || !globalNotesIndex.length) {
    container.innerHTML = `
      <div class="p-8 text-center text-slate-500 text-xs font-semibold">
        No study notes loaded yet. Run <code class="text-emerald-500 font-mono">syncAllNotesToGitHub()</code> in Apps Script!
      </div>`;
    return;
  }

  const subjects = [...new Set(globalNotesIndex.map(n => n.subject))];

  let html = `
    <div class="h-full flex flex-col space-y-3 overflow-hidden">
      <!-- Subject Tabs & Toolbar -->
      <div class="flex flex-wrap items-center justify-between gap-3 border-b border-slate-200 dark:border-slate-800 pb-2 shrink-0">
        <div class="flex flex-wrap items-center gap-2">
          ${subjects.map((sub, idx) => `
            <button 
              type="button"
              onclick="selectSubject('${sub}')" 
              class="tab-btn px-3.5 py-1.5 rounded-xl text-xs font-bold transition-all cursor-pointer ${idx === 0 ? 'bg-emerald-500 text-slate-950 shadow-md shadow-emerald-500/20' : 'bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700'}"
              data-subject="${sub}">
              ${sub}
            </button>
          `).join('')}
        </div>

        <!-- Sidebar Collapse Toggle Button -->
        <button 
          type="button" 
          onclick="toggleSidebar()" 
          id="sidebarToggleBtn"
          class="px-3 py-1.5 bg-slate-100 dark:bg-slate-800 hover:bg-slate-200 dark:hover:bg-slate-700 text-slate-700 dark:text-slate-300 text-xs font-bold rounded-xl border border-slate-200 dark:border-slate-700 transition flex items-center gap-1.5 cursor-pointer">
          <span id="sidebarToggleIcon">◀</span> <span id="sidebarToggleText">Hide Sidebar</span>
        </button>
      </div>

      <!-- Main Content Split Grid -->
      <div class="flex-1 grid grid-cols-12 gap-4 min-h-0 overflow-hidden relative">
        
        <!-- Left: Syllabus Sidebar -->
        <div id="syllabusSidebarCol" class="col-span-12 lg:col-span-4 flex flex-col space-y-3 border-r border-slate-200 dark:border-slate-800 pr-3 overflow-hidden transition-all duration-300">
          <input 
            type="text" 
            id="subjectSearchInput" 
            placeholder="Search topics or keywords..." 
            oninput="handleSubjectSearch()"
            class="w-full px-3.5 py-2 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl text-xs text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:ring-2 focus:ring-emerald-500 outline-none shrink-0"
          />
          <div id="syllabusView" class="flex-1 overflow-y-auto pr-1 space-y-3"></div>
        </div>
        
        <!-- Right: Note Reading & AI Area -->
        <div id="noteReaderCol" class="col-span-12 lg:col-span-8 flex flex-col bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl overflow-hidden transition-all duration-300">
          
          <!-- Viewport Action Header -->
          <div class="px-4 py-2 bg-slate-50 dark:bg-slate-950/80 border-b border-slate-200 dark:border-slate-800 flex justify-between items-center shrink-0">
            <span class="text-[11px] font-bold text-slate-500 dark:text-slate-400 uppercase tracking-wider" id="activeNoteTitle">Note Viewer</span>
            <button 
              type="button" 
              onclick="toggleReaderMaximize()" 
              id="maximizeBtn"
              class="text-[11px] font-bold text-emerald-600 dark:text-emerald-400 hover:underline cursor-pointer flex items-center gap-1">
              <span>⛶</span> <span id="maximizeBtnText">Maximize View</span>
            </button>
          </div>

          <!-- Note Content Area -->
          <div id="noteReaderArea" class="flex-1 p-6 overflow-y-auto text-xs leading-relaxed text-slate-800 dark:text-slate-200">
            <div class="h-full flex flex-col items-center justify-center text-slate-400 dark:text-slate-500 italic text-center">
              👈 Select any subtopic on the left to read notes.
            </div>
          </div>

        </div>

      </div>
    </div>
  `;

  container.innerHTML = html;
  if (subjects.length > 0) selectSubject(subjects[0]);
}

// 3. Toggle Sidebar Leftwards
function toggleSidebar() {
  const sidebar = document.getElementById('syllabusSidebarCol');
  const reader = document.getElementById('noteReaderCol');
  const icon = document.getElementById('sidebarToggleIcon');
  const text = document.getElementById('sidebarToggleText');
  if (!sidebar || !reader) return;

  isSidebarOpen = !isSidebarOpen;

  if (isSidebarOpen) {
    sidebar.classList.remove('hidden');
    sidebar.classList.add('lg:col-span-4');
    reader.classList.remove('lg:col-span-12');
    reader.classList.add('lg:col-span-8');
    if (icon) icon.innerText = '◀';
    if (text) text.innerText = 'Hide Sidebar';
  } else {
    sidebar.classList.add('hidden');
    sidebar.classList.remove('lg:col-span-4');
    reader.classList.remove('lg:col-span-8');
    reader.classList.add('lg:col-span-12');
    if (icon) icon.innerText = '▶';
    if (text) text.innerText = 'Show Sidebar';
  }
}

// 4. Toggle Maximize Note Viewport
function toggleReaderMaximize() {
  const sidebar = document.getElementById('syllabusSidebarCol');
  const reader = document.getElementById('noteReaderCol');
  const text = document.getElementById('maximizeBtnText');

  isReaderMaximized = !isReaderMaximized;

  if (isReaderMaximized) {
    if (sidebar) sidebar.classList.add('hidden');
    if (reader) {
      reader.classList.remove('lg:col-span-8');
      reader.classList.add('lg:col-span-12');
    }
    if (text) text.innerText = 'Restore Split View';
  } else {
    if (isSidebarOpen && sidebar) sidebar.classList.remove('hidden');
    if (reader) {
      reader.classList.remove('lg:col-span-12');
      reader.classList.add(isSidebarOpen ? 'lg:col-span-8' : 'lg:col-span-12');
    }
    if (text) text.innerText = 'Maximize View';
  }
}

// 5. Select Subject
function selectSubject(subjectName) {
  currentSubject = subjectName;
  
  document.querySelectorAll('.tab-btn').forEach(btn => {
    const isSelected = btn.getAttribute('data-subject') === subjectName;
    if (isSelected) {
      btn.className = 'tab-btn px-3.5 py-1.5 rounded-xl text-xs font-extrabold bg-emerald-500 text-slate-950 shadow-md shadow-emerald-500/20 transition-all cursor-pointer';
    } else {
      btn.className = 'tab-btn px-3.5 py-1.5 rounded-xl text-xs font-bold bg-slate-100 dark:bg-slate-800 text-slate-600 dark:text-slate-300 hover:bg-slate-200 dark:hover:bg-slate-700 transition-all cursor-pointer';
    }
  });

  const searchInput = document.getElementById('subjectSearchInput');
  if (searchInput) searchInput.value = "";

  renderSyllabusTree(globalNotesIndex.filter(n => n.subject === subjectName));
}

// 6. Render Syllabus Tree
function renderSyllabusTree(notesList) {
  const view = document.getElementById('syllabusView');
  if (!view) return;

  if (!notesList.length) {
    view.innerHTML = `<div class="p-4 text-center text-xs text-slate-500">No matching subtopics.</div>`;
    return;
  }

  const units = {};
  notesList.forEach(item => {
    const unitName = item.unit || "General Unit";
    if (!units[unitName]) units[unitName] = [];
    units[unitName].push(item);
  });

  let html = `<div class="space-y-3">`;
  for (const [unitName, subtopics] of Object.entries(units)) {
    html += `
      <div class="space-y-1.5">
        <h4 class="text-[10px] font-extrabold uppercase tracking-wider text-emerald-600 dark:text-emerald-400 border-b border-slate-200 dark:border-slate-800/60 pb-1">
          ${unitName}
        </h4>
        <div class="space-y-1">
          ${subtopics.map(st => `
            <button 
              type="button"
              onclick="loadNoteContent('${st.filePath}', '${st.title.replace(/'/g, "\\'")}')"
              class="w-full text-left p-2 rounded-xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 hover:border-emerald-500 dark:hover:border-emerald-500 text-xs font-medium text-slate-800 dark:text-slate-200 transition-all cursor-pointer flex items-center justify-between group">
              <span class="truncate pr-2">${st.title}</span>
              <span class="text-slate-400 group-hover:text-emerald-500 shrink-0">&rarr;</span>
            </button>
          `).join('')}
        </div>
      </div>
    `;
  }
  html += `</div>`;
  view.innerHTML = html;
}

// 7. Search Engine Filtering
function handleSubjectSearch() {
  const query = document.getElementById('subjectSearchInput').value.toLowerCase().trim();
  
  if (!query) {
    renderSyllabusTree(globalNotesIndex.filter(n => n.subject === currentSubject));
    return;
  }

  const filtered = globalNotesIndex.filter(n => {
    if (n.subject !== currentSubject) return false;
    const matchTitle = n.title.toLowerCase().includes(query);
    const matchKeyword = n.keywords && n.keywords.some(k => k.toLowerCase().includes(query));
    return matchTitle || matchKeyword;
  });

  renderSyllabusTree(filtered);
}

// 8. Live Fetch Note Content
async function loadNoteContent(filePath, title = "Note Viewer") {
  const reader = document.getElementById('noteReaderArea');
  const titleTag = document.getElementById('activeNoteTitle');
  if (titleTag) titleTag.innerText = title;
  if (!reader) return;

  reader.innerHTML = `
    <div class="h-full flex flex-col items-center justify-center py-12 gap-2 text-slate-500">
      <div class="w-6 h-6 border-2 border-emerald-500 border-t-transparent rounded-full animate-spin"></div>
      <span class="text-xs font-semibold">Loading note content...</span>
    </div>`;

  try {
    const res = await fetch(filePath);
    const html = await res.text();
    reader.innerHTML = html;
  } catch (err) {
    reader.innerHTML = `<div class="text-xs text-rose-500 font-bold p-4">Error loading note content from GitHub.</div>`;
  }
}

document.addEventListener('DOMContentLoaded', initStudyEngine);
